"""
Produce a LaTeX-ready results table comparing methods at the end of training.
File: scripts/results_table.py
"""

from __future__ import annotations
import argparse
import re
from pathlib import Path
import numpy as np

LOG_PATTERN = re.compile(r"(?:steps|Steps)=\s*(\d+)\s+(?:mean_ret|MeanReturn)[^=]*=\s*([\-\d.]+)")

PRETTY_NAMES = {
    "nocomm":   "Independent No-Comm Baseline",
    "fccomm":   "Fully-Connected Comm Baseline",
    "attncomm": "Selective Attention Comm",
    "gnncomm":  "Relational GNN Comm"
}

def parse_final_return(path: Path, tail: int = 5) -> tuple[int, float] | None:
    """Averages the last N reported steps to denoise performance metrics."""
    steps, rets = [], []
    with path.open() as f:
        for line in f:
            m = LOG_PATTERN.search(line)
            if m:
                steps.append(int(m.group(1)))
                rets.append(float(m.group(2)))
    if not rets:
        return None
    return steps[-1], float(np.mean(rets[-tail:]))

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--logs-dir", default="logs")
    ap.add_argument("--methods", nargs="+", default=["nocomm", "fccomm"])
    ap.add_argument("--out", default="tables/day4_results.tex")
    ap.add_argument("--tail", type=int, default=5)
    args = ap.parse_args()

    logs_dir = Path(args.logs_dir)
    out_tex = Path(args.out)
    out_tex.parent.mkdir(parents=True, exist_ok=True)

    rows = []
    for method in args.methods:
        files = sorted(logs_dir.glob(f"{method}_seed*.log"))
        finals = []
        last_steps = []
        for f in files:
            r = parse_final_return(f, tail=args.tail)
            if r is None:
                continue
            last_steps.append(r[0])
            finals.append(r[1])
        if not finals:
            continue

        rows.append({
            "method": method,
            "n_seeds": len(finals),
            "last_step": min(last_steps) if last_steps else 0,
            "mean": float(np.mean(finals)),
            "std": float(np.std(finals, ddof=1)) if len(finals) > 1 else 0.0,
        })

    if not rows:
        print("[warn] No completed experiment logs found to build tables from.")
        return

    # 1) Terminal Plain Text Summary
    print("\n=== Experimental Summary ===")
    print(f"{'Method':<32} {'n':>3} {'Steps':>10} {'Mean':>9} {'Std':>9}")
    for r in rows:
        print(f"{r['method']:<32} {r['n_seeds']:>3} {r['last_step']:>10} {r['mean']:>9.2f} {r['std']:>9.2f}")

    # 2) LaTeX Code Block Generation
    lines = [
        "% Auto-generated by results_table.py — do not edit by hand.",
        "\\begin{table}[t]",
        "  \\centering",
        "  \\caption{Final mean episode return comparison on PettingZoo MPE Simple Spread (mean$\\pm$std).}",
        "  \\label{tab:results-simple-spread}",
        "  \\begin{tabular}{lccc}",
        "    \\toprule",
        "    Method & $n$ & Target Steps & Final Return \\\\",
        "    \\midrule"
    ]
    for r in rows:
        name = PRETTY_NAMES.get(r["method"], r["method"])
        lines.append(f"    {name} & {r['n_seeds']} & {r['last_step']} & ${r['mean']:.2f} \\pm {r['std']:.2f}$ \\\\")
    lines.extend([
        "    \\bottomrule",
        "  \\end{tabular}",
        "\\end{table}"
    ])

    tex = "\n".join(lines) + "\n"
    out_tex.write_text(tex)
    print(f"\n[table] Success! Wrote LaTeX snippet to: {out_tex}")
    print("-" * 60)
    print(tex)
    print("-" * 60)

if __name__ == "__main__":
    main()
